export type I18nKey = keyof typeof dictionaries.zh;

interface LangCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: I18nKey) => string;
}

const Ctx = createContext<LangCtx>({ lang: 'zh', setLang: () => {}, t: (k) => k });

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      const stored = localStorage.getItem('aether-lang');
      return isLang(stored) ? stored : 'zh';
    } catch { return 'zh'; }
  });
  useEffect(() => { try { localStorage.setItem('aether-lang', lang); } catch {} }, [lang]);
  const setLang = (l: Lang) => setLangState(l);
  const t = (k: I18nKey) =>
    (dictionaries[lang] as Record<string, string>)[k] ?? dictionaries.zh[k] ?? k;
  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
};

export const useLang = () => useContext(Ctx);
